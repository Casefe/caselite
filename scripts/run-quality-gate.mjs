import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const mode = process.argv[2] ?? 'quick';
const commands = {
  quick: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
  ],
  ci: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
    ['dependency-audit', ['audit:dependencies']],
    ['license-report', ['licenses:report']],
    ['integration', ['test:integration'], 'not-run'],
    ['e2e', ['test:e2e'], 'not-run'],
  ],
  full: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
    ['dependency-audit', ['audit:dependencies']],
    ['license-report', ['licenses:report']],
    ['integration', ['test:integration'], 'not-run'],
    ['e2e', ['test:e2e'], 'not-run'],
    ['macos-package', ['package']],
  ],
};

if (mode === 'evidence') {
  console.log('Evidence files are generated by pnpm check:quick, pnpm ci, or pnpm test:full.');
  process.exit(0);
}

if (!commands[mode]) {
  console.error(`Unknown quality-gate mode: ${mode}`);
  process.exit(1);
}

function run(command, args) {
  return execFileSync(command, args, { cwd: repositoryRoot, encoding: 'utf8' }).trim();
}

const startedAt = new Date();
const results = [];

for (const [name, args, presetStatus] of commands[mode]) {
  const command = ['pnpm', ...args];
  const started = Date.now();
  console.log(`\n==> ${command.join(' ')}`);
  const result = spawnSync(command[0], command.slice(1), {
    cwd: repositoryRoot,
    encoding: 'utf8',
    stdio: 'inherit',
  });
  results.push({
    command: command.join(' '),
    durationMs: Date.now() - started,
    name,
    status: result.status === 0 ? (presetStatus ?? 'passed') : 'failed',
  });
  if (result.status !== 0) break;
}

const evidence = {
  commit: run('git', ['rev-parse', 'HEAD']),
  mode,
  node: process.version,
  pnpm: run('pnpm', ['--version']),
  recovery: 'Delete generated artifacts/, correct the failure, then rerun the same command.',
  results,
  startedAt: startedAt.toISOString(),
  unverified: [
    'Integration tests are not configured until SQLite, files and typed IPC exist.',
    'Playwright Electron automation is deferred because the current security Fuse intentionally disables the inspect argument it requires.',
    ...(mode === 'ci'
      ? [
          'macOS desktop packaging is intentionally verified on the Apple Silicon development machine, not the Linux CI runner.',
        ]
      : []),
  ],
};

const evidenceDirectory = resolve(repositoryRoot, 'artifacts/evidence');
mkdirSync(evidenceDirectory, { recursive: true });
const evidenceFile = resolve(
  evidenceDirectory,
  `g0-${mode}-${startedAt.toISOString().replaceAll(':', '-')}.json`,
);
writeFileSync(evidenceFile, `${JSON.stringify(evidence, null, 2)}\n`);
console.log(`\nEvidence written to artifacts/evidence/${evidenceFile.split('/').pop()}`);

if (results.some((result) => result.status === 'failed')) process.exitCode = 1;
