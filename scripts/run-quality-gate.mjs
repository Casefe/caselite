import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { executePlan } from './lib/quality-results.mjs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const mode = process.argv[2] ?? 'quick';
const commands = {
  quick: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['quality-changes', ['review:changes']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
    ['license-report', ['licenses:report']],
  ],
  ci: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['quality-changes', ['review:changes']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
    ['dependency-audit', ['audit:dependencies']],
    ['license-report', ['licenses:report']],
    ['integration', ['test:integration']],
    ['coverage', ['coverage']],
    ['e2e', ['exec', 'node', 'scripts/report-not-run.mjs', 'e2e'], 'not-run'],
  ],
  full: [
    ['format', ['format:check']],
    ['lint', ['lint']],
    ['architecture', ['architecture:check']],
    ['test-integrity', ['test:integrity']],
    ['quality-changes', ['review:changes']],
    ['security-baseline', ['security:baseline']],
    ['typecheck', ['typecheck']],
    ['unit', ['test:unit']],
    ['contracts', ['test:contracts']],
    ['dependency-audit', ['audit:dependencies']],
    ['license-report', ['licenses:report']],
    ['integration', ['test:integration']],
    ['coverage', ['coverage']],
    ['macos-package', ['package']],
    ['macos-desktop-e2e', ['test:e2e']],
  ],
};

if (mode === 'evidence') {
  console.log('Evidence files are generated by pnpm check:quick, pnpm ci, or pnpm test:full.');
  process.exit(0);
}

if (!commands[mode]) {
  console.error(`Unknown quality-gate mode: ${mode}`);
  process.exit(1);
}

function run(command, args) {
  return execFileSync(command, args, { cwd: repositoryRoot, encoding: 'utf8' }).trim();
}

const startedAt = new Date();
const trackedAndUntracked = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], {
  cwd: repositoryRoot,
  encoding: 'utf8',
})
  .split('\0')
  .filter(Boolean)
  .sort();
const sourceHash = createHash('sha256');
for (const file of trackedAndUntracked) {
  sourceHash
    .update(file)
    .update('\0')
    .update(
      existsSync(resolve(repositoryRoot, file))
        ? readFileSync(resolve(repositoryRoot, file))
        : '<deleted>',
    )
    .update('\0');
}
const identity = {
  commit: run('git', ['rev-parse', 'HEAD']),
  dirty: run('git', ['status', '--porcelain']).length > 0,
  worktreeSha256: sourceHash.digest('hex'),
  lockfileSha256: createHash('sha256')
    .update(readFileSync(resolve(repositoryRoot, 'pnpm-lock.yaml')))
    .digest('hex'),
};
const results = executePlan(commands[mode], (args) => {
  console.log(`\n==> pnpm ${args.join(' ')}`);
  return spawnSync('pnpm', args, {
    cwd: repositoryRoot,
    encoding: 'utf8',
    stdio: 'inherit',
  });
});

const evidence = {
  ...identity,
  mode,
  node: process.version,
  pnpm: run('pnpm', ['--version']),
  recovery: 'Delete generated artifacts/, correct the failure, then rerun the same command.',
  results,
  startedAt: startedAt.toISOString(),
  unverified: [
    'Formal Matter/Anchor and arbitrary customer file integration are not implemented; inspect individual results for checks actually run.',
    'Playwright Electron automation is deferred because the current security Fuse intentionally disables the inspect argument it requires.',
    ...(mode === 'ci'
      ? [
          'The packaged PDF + IPC + SQLite restart test runs only on an interactive macOS Apple Silicon host.',
        ]
      : []),
    ...(mode === 'ci'
      ? [
          'macOS desktop packaging is intentionally verified on the Apple Silicon development machine, not the Linux CI runner.',
        ]
      : []),
  ],
};
evidence.status = results.some((result) => result.status === 'failed')
  ? 'failed'
  : 'passed-with-limitations';
evidence.unverified.push(
  ...results
    .filter((result) => result.status !== 'passed')
    .map(
      (result) => `${result.name}: ${result.status}${result.reason ? ` (${result.reason})` : ''}`,
    ),
);

const evidenceDirectory = resolve(repositoryRoot, 'artifacts/evidence');
mkdirSync(evidenceDirectory, { recursive: true });
const evidenceFile = resolve(
  evidenceDirectory,
  `g0-${mode}-${startedAt.toISOString().replaceAll(':', '-')}.json`,
);
writeFileSync(evidenceFile, `${JSON.stringify(evidence, null, 2)}\n`);
console.log(`\nEvidence written to artifacts/evidence/${evidenceFile.split('/').pop()}`);

if (results.some((result) => result.status === 'failed')) process.exitCode = 1;
